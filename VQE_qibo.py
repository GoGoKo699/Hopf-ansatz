    plt.axhline(E_exact, linestyle="--", color="gray", label="Exact ground energy")
    plt.xlabel("Iteration")
    plt.ylabel("Energy")
    plt.title("VQE with Real Hopf Ansatz (Qibo)")
    plt.legend()
