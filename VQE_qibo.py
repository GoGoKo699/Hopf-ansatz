"""VQE_qibo.py
================================================================================
Circuit-level safeguard for the real Hopf ansatz gradient formula.

This script is separate from the layerwise numerical panel. It uses Qibo to
build explicit ancilla circuits for transition-moment estimation. For each
Hopf coordinate i and Pauli term P_alpha, it prepares a coherent superposition
of the current Hopf state and the normalized tangent state, applies a controlled
Pauli operation, and estimates the real transition moment

    Re <partial_i psi(theta)| P_alpha |psi(theta)>.

The tangent state is generated by hopf_utils.theta_hopf_tangent_state, using the
same Hopf circuit skeleton as the forward ansatz. The resulting sampled
Hadamard-test gradient is compared against the exact state-vector gradient in a
small TFIM VQE run.

This file is a circuit-realizability check. The main paper plots use the
layerwise signed-branch estimators in VQE_Layerwise_ADAM_EGTCG.py and
MET_Layerwise_ADAM_EGTCG.py.

Output:
    * VQE_ADAM_MC_qibo.pdf.
    * Console logs comparing exact-gradient and circuit-sampled trajectories.

Dependencies: numpy, matplotlib, qibo, hopf_utils.
================================================================================
"""

import math
import numpy as np
import matplotlib.pyplot as plt
from qibo import models, gates
from hopf_utils import (
    qibo_circuit, gates_order, canonical_initial_state, 
    theta_from_vector, clip_theta_hopf_real, 
    theta_hopf_tangent_state, partial_derivative_column_real,
    vector_from_theta
)

def init_theta_from_canonical_state(n: int, seed: int = 123):
    psi0 = canonical_initial_state(n, seed)
    # Using 'real' case for theta_from_vector
    theta0 = clip_theta_hopf_real(theta_from_vector(psi0, 'real'), n=n)
    return theta0

# ---------------------------
# TFIM Hamiltonian (n-qubit, open boundary)
# ---------------------------

def kron_n(ops):
    out = ops[0]
    for m in ops[1:]:
        out = np.kron(out, m)
    return out

def tfim_hamiltonian(n=6, J=1.0, h=0.6):
    I = np.eye(2)
    X = np.array([[0.0, 1.0], [1.0, 0.0]], dtype=float)
    Z = np.array([[1.0, 0.0], [0.0,-1.0]], dtype=float)
    H = np.zeros((1 << n, 1 << n), dtype=float)
    for i in range(n - 1):
        ops = [I] * n
        ops[i], ops[i + 1] = Z, Z
        H -= J * kron_n(ops)
    for i in range(n):
        ops = [I] * n
        ops[i] = X
        H -= h * kron_n(ops)
    return H

def decompose_H_terms(n=6, J=1.0, h=0.6):
    terms = []
    for i in range(n - 1):
        terms.append((-J, ('ZZ', i, i+1)))
    for i in range(n):
        terms.append((-h, ('X', i)))
    return terms

def pauli_string_matrix(term, n):
    I = np.eye(2)
    X = np.array([[0.0, 1.0], [1.0, 0.0]], dtype=float)
    Z = np.array([[1.0, 0.0], [0.0,-1.0]], dtype=float)
    ops = [I] * n
    kind = term[0]
    if kind == 'X':
        i = term[1]
        ops[i] = X
    elif kind == 'Z':
        i = term[1]
        ops[i] = Z
    elif kind == 'ZZ':
        i, j = term[1], term[2]
        ops[i] = Z
        ops[j] = Z
    else:
        raise ValueError(f"Unsupported term label: {term}")
    return kron_n(ops)

def build_decomposition(n=6, J=1.0, h=0.6):
    labeled = decompose_H_terms(n, J, h)
    coeffs = np.array([float(c) for c, _ in labeled], dtype=float)
    labels = [t for _, t in labeled]
    Pmats  = [pauli_string_matrix(t, n) for t in labels]
    return coeffs, labels, Pmats


